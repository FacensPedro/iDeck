#!/usr/bin/env python3
"""Write an i386 vulkan-1.dll stand-in from Wine's vulkan-1.spec.

The x86 runtime is built without Vulkan (build/wine-i386/build.sh: the tree is
--without-vulkan, graphics go through DXMT), so it has no vulkan-1.dll, and a 32-bit
game whose import table names it stopped in the loader with STATUS_DLL_NOT_FOUND
before running. This stand-in exports every name Wine's own vulkan-1 exports and
answers like the Khronos loader on a PC without a Vulkan driver, as Madeira's
ARM64EC stand-in does (tools/build-stub-dlls.py): the global commands work
(vkEnumerateInstanceVersion reports 1.3, the instance extension and layer lists
are empty), vkCreateInstance and every other call report
VK_ERROR_INCOMPATIBLE_DRIVER, vkGetInstanceProcAddr hands out only the global
commands. A game then falls back to Direct3D.

Vulkan's 32-bit calling convention is stdcall: the callee pops its arguments, so
each stand-in takes exactly the argument sizes the spec lists (int64 is 8 bytes).

Usage: gen_vulkan1.py <vulkan-1.spec> <output .c>
"""
import re
import sys

SIZES = {"ptr": 4, "long": 4, "str": 4, "wstr": 4, "float": 4, "int64": 8, "double": 8}
CTYPES = {"ptr": "void *", "long": "int", "str": "const char *", "wstr": "const void *",
          "float": "float", "int64": "unsigned long long", "double": "double"}
GLOBAL = ("vkEnumerateInstanceVersion", "vkEnumerateInstanceExtensionProperties",
          "vkEnumerateInstanceLayerProperties", "vkCreateInstance", "vkGetInstanceProcAddr")
BODIES = {
    "vkEnumerateInstanceVersion": "if (a0) *(unsigned *)a0 = (1u << 22) | (3u << 12); return 0;",
    "vkEnumerateInstanceExtensionProperties": "if (a0) return -6; if (a1) *(unsigned *)a1 = 0; return 0;",
    "vkEnumerateInstanceLayerProperties": "if (a0) *(unsigned *)a0 = 0; return 0;",
    "vkCreateInstance": "if (a2) *(void **)a2 = 0; return -9;",
}


def parse(path):
    functions = []
    for line in open(path):
        line = line.split("#", 1)[0].strip()
        match = re.match(r"@\s+stdcall\s+(?:-\S+\s+)*(\w+)\s*\(([^)]*)\)", line)
        if match:
            name, args = match.group(1), match.group(2).split()
            for arg in args:
                if arg not in SIZES:
                    raise SystemExit(f"unknown argument type {arg} in {name}")
            functions.append((name, args))
    if not functions:
        raise SystemExit(f"no stdcall exports in {path}")
    return functions


def main(spec, output):
    functions = parse(spec)
    names = {name for name, _ in functions}
    missing = [g for g in GLOBAL if g not in names]
    if missing:
        raise SystemExit("vulkan-1.spec lacks " + ", ".join(missing))
    lines = ["/* Generated by gen_vulkan1.py from Wine's vulkan-1.spec. Do not edit. */",
             "#define VK_ERROR_INCOMPATIBLE_DRIVER (-9)", ""]
    for name, args in functions:
        params = ", ".join(f"{CTYPES[a]} a{i}" for i, a in enumerate(args)) or "void"
        unused = " ".join(f"(void)a{i};" for i in range(len(args)))
        if name == "vkGetInstanceProcAddr":
            continue
        returns = "void *" if name.endswith("ProcAddr") else "int"
        body = BODIES.get(name, "return 0;" if returns == "void *" else "return VK_ERROR_INCOMPATIBLE_DRIVER;")
        lines.append(f"{returns} __stdcall {name}({params}) {{ {unused} {body} }}")
        size = sum(SIZES[a] for a in args)
        lines.append(f'__asm__(".section .drectve\\n.ascii \\" -export:{name}={name}@{size}\\"\\n.text");')
    lines += ["",
              "void * __stdcall vkGetInstanceProcAddr(void *instance, const char *name)",
              "{",
              "    static const struct { const char *n; void *f; } global[] = {"]
    lines += [f'        {{ "{g}", (void *){g} }},' for g in GLOBAL]
    lines += ["    };",
              "    unsigned i, k;",
              "    (void)instance;",
              "    if (!name) return 0;",
              "    for (i = 0; i < sizeof(global) / sizeof(global[0]); i++) {",
              "        for (k = 0; global[i].n[k] && global[i].n[k] == name[k]; k++) ;",
              "        if (!global[i].n[k] && !name[k]) return global[i].f;",
              "    }",
              "    return 0;",
              "}",
              '__asm__(".section .drectve\\n.ascii \\" -export:vkGetInstanceProcAddr=vkGetInstanceProcAddr@8\\"\\n.text");',
              ""]
    open(output, "w").write("\n".join(lines))
    print(f"vulkan-1 stand-in: {len(functions)} exports")


if __name__ == "__main__":
    main(*sys.argv[1:3])
