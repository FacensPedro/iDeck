#!/usr/bin/env python3
"""iDeckSystemLibraries: the catalog of public iOS frameworks iDeck uses or may use,
and a coverage report built from the source code (Swift imports, Objective-C/C
#import/#include of <Framework/...>). Frameworks are part of iOS: nothing is copied
into the IPA. The report is regenerated by CI and must be up to date.

  scripts/ios_system_libraries.py            # write docs/ios-system-libraries.{md,json}
  scripts/ios_system_libraries.py --check    # fail when the committed report is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# iDeck's own sources only: the Madeira checkout is not in every CI job, and the report
# must come out the same everywhere.
SOURCES = [ROOT / "iDeck"]
SKIP_PARTS = {"FEX", "wine", "dxmt", "research", "toolchains", "tests"}

# name -> (group, minimum iOS, public status / note)
CATALOG = {
    "Foundation": ("Core System", "2.0", "public"), "CoreFoundation": ("Core System", "2.0", "public"),
    "Darwin": ("Core System", "2.0", "public (libSystem)"), "os": ("Core System", "10.0", "public"),
    "Dispatch": ("Core System", "4.0", "public"), "CoreServices": ("Core System", "12.0", "public (MobileCoreServices on older)"),
    "SystemConfiguration": ("Core System", "2.0", "public"), "Combine": ("Core System", "13.0", "public"),
    "MachO": ("Core System", "2.0", "public (libSystem)"),
    "UIKit": ("Interface", "2.0", "public"), "SwiftUI": ("Interface", "13.0", "public"),
    "CoreGraphics": ("Graphics", "2.0", "public"), "QuartzCore": ("Graphics", "2.0", "public (Core Animation)"),
    "CoreImage": ("Graphics", "5.0", "public"), "CoreVideo": ("Graphics", "4.0", "public"),
    "IOSurface": ("Graphics", "11.0", "public"), "Metal": ("Graphics", "8.0", "public"),
    "MetalKit": ("Graphics", "9.0", "public"), "MetalFX": ("Graphics", "16.0", "public"),
    "MetalPerformanceShaders": ("Graphics", "9.0", "public"), "Accelerate": ("Graphics", "4.0", "public"),
    "ImageIO": ("Graphics", "4.0", "public"), "CoreText": ("Graphics", "3.2", "public"),
    "OpenGLES": ("Graphics", "2.0", "public, deprecated"),
    "AVFoundation": ("Audio & video", "2.2", "public"), "CoreAudio": ("Audio & video", "2.0", "public"),
    "AudioToolbox": ("Audio & video", "2.0", "public"), "CoreMedia": ("Audio & video", "4.0", "public"),
    "VideoToolbox": ("Audio & video", "8.0", "public"), "AVKit": ("Audio & video", "8.0", "public"),
    "Network": ("Network", "12.0", "public"), "CFNetwork": ("Network", "2.0", "public"),
    "NetworkExtension": ("Network", "8.0", "public, entitlement"), "MultipeerConnectivity": ("Network", "7.0", "public"),
    "GameKit": ("Network", "3.0", "public"),
    "Security": ("Security", "2.0", "public"), "LocalAuthentication": ("Security", "8.0", "public"),
    "AuthenticationServices": ("Security", "12.0", "public"), "CryptoKit": ("Security", "13.0", "public"),
    "CommonCrypto": ("Security", "2.0", "public (libSystem)"),
    "CoreData": ("Files & storage", "3.0", "public"), "FileProvider": ("Files & storage", "11.0", "public"),
    "UniformTypeIdentifiers": ("Files & storage", "14.0", "public"), "QuickLook": ("Files & storage", "4.0", "public"),
    "Compression": ("Files & storage", "9.0", "public"), "SQLite": ("Files & storage", "2.0", "public (libsqlite3)"),
    "CoreTransferable": ("Files & storage", "16.0", "public"),
    "CoreMotion": ("System & devices", "4.0", "public"), "ExternalAccessory": ("System & devices", "3.0", "public, MFi"),
    "CoreHaptics": ("System & devices", "13.0", "public"), "BackgroundTasks": ("System & devices", "13.0", "public"),
    "IOKit": ("System & devices", "-", "not public on iOS: not to be used"), "MetricKit": ("System & devices", "13.0", "public"),
    "GameController": ("System & devices", "7.0", "public"), "UserNotifications": ("System & devices", "10.0", "public"),
}
NOT_IOS = {"AppKit", "Glibc", "FoundationNetworking", "FoundationXML", "zlib"}   # other platforms / non-framework
C_ALIASES = {"dispatch": "Dispatch", "mach": "Darwin", "sys": "Darwin", "libkern": "Darwin", "objc": "Darwin"}

SWIFT = re.compile(r"^\s*(?:@\w+\s+)*import\s+(?:(?:struct|class|enum|func|protocol|typealias|var|let)\s+)?([A-Za-z_]+)", re.M)
OBJC = re.compile(r"#\s*(?:import|include)\s*<([A-Za-z_]+)/")


def scan():
    uses = {}
    for base in SOURCES:
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if not path.is_file() or path.suffix not in {".swift", ".m", ".mm", ".h", ".c", ".cpp"}:
                continue
            if SKIP_PARTS & set(path.relative_to(ROOT).parts):
                continue
            text = path.read_text(errors="ignore")
            names = SWIFT.findall(text) if path.suffix == ".swift" else OBJC.findall(text)
            for name in names:
                name = C_ALIASES.get(name, name)
                if name in CATALOG:
                    uses.setdefault(name, set()).add(str(path.relative_to(ROOT)))
    return uses


def report():
    uses = scan()
    rows = []
    for name, (group, minimum, status) in sorted(CATALOG.items(), key=lambda kv: (kv[1][0], kv[0])):
        files = sorted(uses.get(name, []))
        rows.append({"framework": name, "group": group, "minimum_ios": minimum, "status": status,
                     "used": bool(files), "files": len(files), "examples": files[:3]})
    usable = [r for r in rows if not r["status"].startswith("not public")]
    used = [r for r in usable if r["used"]]
    summary = {"catalogued": len(rows), "public": len(usable), "used": len(used),
               "coverage_percent": round(100 * len(used) / max(len(usable), 1), 1)}
    data = {"module": "iDeckSystemLibraries", "summary": summary, "frameworks": rows}
    md = ["# iDeck System Libraries", "",
          "Public iOS frameworks iDeck uses or may use. They ship with iOS; nothing is copied into the IPA.",
          "Generated by `scripts/ios_system_libraries.py` from the source code; CI fails when it is out of date.", "",
          f"**Coverage: {summary['used']} of {summary['public']} public frameworks in use ({summary['coverage_percent']}%).**", "",
          "| Group | Framework | Min. iOS | Status | In use | Files |", "|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['group']} | {r['framework']} | {r['minimum_ios']} | {r['status']} | {'yes' if r['used'] else 'no'} | {r['files']} |")
    return json.dumps(data, indent=2, sort_keys=True) + "\n", "\n".join(md) + "\n"


def main():
    js, md = report()
    jp, mp = ROOT / "docs" / "ios-system-libraries.json", ROOT / "docs" / "ios-system-libraries.md"
    if "--check" in sys.argv:
        if not jp.exists() or jp.read_text() != js or mp.read_text() != md:
            print("docs/ios-system-libraries.* is out of date: run scripts/ios_system_libraries.py", file=sys.stderr)
            return 1
        return 0
    jp.parent.mkdir(exist_ok=True)
    jp.write_text(js)
    mp.write_text(md)
    print(md.splitlines()[5])
    return 0


if __name__ == "__main__":
    sys.exit(main())
